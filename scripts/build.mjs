// Builds the site into dist/ and writes dist/config.js from environment variables,
// so Supabase settings live in Vercel (or a local .env.local), never in the repo.
//
// Note: config.js is still downloaded by every visitor's browser. That is fine for the
// publishable key (it's designed to be public); this script refuses to build with a secret key.
//
// Run locally:  node scripts/build.mjs   (reads .env.local if present; empty = demo mode)

import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "dist");

/* ---------- 1. Read settings ---------- */
// .env.local for local runs; real environment variables (Vercel) win over it
const envFile = join(ROOT, ".env.local");
const fileEnv = {};
if (existsSync(envFile)) {
  for (const line of readFileSync(envFile, "utf8").split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (m) fileEnv[m[1]] = m[2].replace(/^(['"])(.*)\1$/, "$2");
  }
}
const env = (name) => (process.env[name] ?? fileEnv[name] ?? "").trim();

const supabaseUrl = env("SUPABASE_URL").replace(/\/+$/, "");
const supabasePublishableKey = env("SUPABASE_PUBLISHABLE_KEY");
const adminEmailDomain = env("ADMIN_EMAIL_DOMAIN") || "example.com";
// SITE_URL if set, else Vercel's production domain (set automatically on Vercel)
const siteUrl = (env("SITE_URL") ||
  (env("VERCEL_PROJECT_PRODUCTION_URL") && `https://${env("VERCEL_PROJECT_PRODUCTION_URL")}`)).replace(/\/+$/, "");

/* ---------- 2. Refuse unsafe or half-done settings ---------- */
const fail = (msg) => { console.error(`\n✖ Build stopped: ${msg}\n`); process.exit(1); };

if (/^sb_secret_/.test(supabasePublishableKey)) {
  fail("SUPABASE_PUBLISHABLE_KEY is a SECRET key (sb_secret_…). Use the publishable key, and rotate the secret key in Supabase now.");
}
if (/^eyJ/.test(supabasePublishableKey)) {
  try {
    const payload = JSON.parse(Buffer.from(supabasePublishableKey.split(".")[1], "base64url").toString());
    if (payload.role !== "anon") fail(`SUPABASE_PUBLISHABLE_KEY has role "${payload.role}". Only the anon/publishable key may be used.`);
  } catch { fail("SUPABASE_PUBLISHABLE_KEY looks like a JWT but can't be read."); }
}
if (!!supabaseUrl !== !!supabasePublishableKey) {
  fail("Set both SUPABASE_URL and SUPABASE_PUBLISHABLE_KEY, or neither (demo mode).");
}
if (supabaseUrl && !/^https:\/\/[a-z0-9-]+\.supabase\.co$/.test(supabaseUrl)) {
  fail(`SUPABASE_URL should look like https://abcdefghijkl.supabase.co (got "${supabaseUrl}").`);
}
if (siteUrl && !/^https?:\/\/[^\s/]+$/.test(siteUrl)) {
  fail(`SITE_URL should be just the address, e.g. https://rioandolivia.com (got "${siteUrl}").`);
}
// Never ship demo mode to the real site by accident
if (env("VERCEL_ENV") === "production" && !supabaseUrl) {
  fail("SUPABASE_URL and SUPABASE_PUBLISHABLE_KEY are not set for Production in Vercel → Settings → Environment Variables.");
}

/* ---------- 3. Copy only the files the website needs ---------- */
rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT);

const PUBLISH = ["index.html", "admin", "assets"];
const SKIP = [/(^|\/)\.DS_Store$/, /^assets\/img\/_originals(\/|$)/, /(^|\/)\.keep$/];
for (const item of PUBLISH) {
  cpSync(join(ROOT, item), join(OUT, item), {
    recursive: true,
    filter: (src) => !SKIP.some((re) => re.test(relative(ROOT, src))),
  });
}

/* ---------- 4. Write config.js and the link-preview address ---------- */
const config = { supabaseUrl, supabasePublishableKey, adminEmailDomain, siteUrl, maxPax: 5 }; // maxPax must match supabase/setup.sql
writeFileSync(join(OUT, "config.js"),
  "/* Generated by scripts/build.mjs from environment variables. Do not edit. */\n" +
  `window.WEDDING_CONFIG = ${JSON.stringify(config, null, 2)};\n`);

// WhatsApp / iMessage previews need a full image address
const indexPath = join(OUT, "index.html");
const html = readFileSync(indexPath, "utf8");
writeFileSync(indexPath, siteUrl ? html.replaceAll("https://YOUR-SITE", siteUrl) : html);

console.log(`✔ Built dist/ — ${supabaseUrl ? `Supabase ${supabaseUrl}` : "DEMO MODE (nothing is saved)"}` +
  `${siteUrl ? `, site ${siteUrl}` : ", no SITE_URL (link previews won't show an image)"}`);
